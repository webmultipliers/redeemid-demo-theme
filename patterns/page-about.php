<!-- wp:paragraph {"className":"ledger-article__dek"} -->
<p class="ledger-article__dek">The Harborview Ledger is an independent newsroom of eleven reporters and editors covering the harbor, the city and the islands. It is also fiction: a test site for the RedeemID plugin.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"anchor":"free-and-paid"} -->
<h2 class="wp-block-heading" id="free-and-paid">What is free, and what is for members</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>News the whole city needs stays free: council votes, transit, weather, public safety and every correction. Stories that take months, a records request and a lawyer’s review are for members, and so is our most specialised work.</p>
<!-- /wp:paragraph -->

<!-- wp:list {"className":"ledger-about-list"} -->
<ul class="ledger-about-list">
	<!-- wp:list-item -->
	<li><span class="redeemid-access-badge" data-redeemid-level="free">Free</span> Most news, most city guides and every correction. Some members’ stories are opened for everyone when they matter to everyone, like our ferry fuel investigation and the storm briefing.</li>
	<!-- /wp:list-item -->
	<!-- wp:list-item -->
	<li><span class="redeemid-access-badge" data-redeemid-level="signed-in">Signed in</span> A free account opens the briefings, our election coverage and the editorial board.</li>
	<!-- /wp:list-item -->
	<!-- wp:list-item -->
	<li><span class="redeemid-access-badge" data-redeemid-level="silver">Silver</span> The culture desk, features and our Fennel Hill guides.</li>
	<!-- /wp:list-item -->
	<!-- wp:list-item -->
	<li><span class="redeemid-access-badge" data-redeemid-level="gold">Gold</span> Investigations and Ledger Reports. Reports open to everyone after a year.</li>
	<!-- /wp:list-item -->
	<!-- wp:list-item -->
	<li><span class="redeemid-access-badge" data-redeemid-level="premium">Gold + Silver</span> Stories that cross both desks, and the Harbor Money series.</li>
	<!-- /wp:list-item -->
</ul>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p>Every story shows its badge in lists and at the top of the page, so you know before you click. If a story is locked, you will see its first paragraphs and a way to join or sign in.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">How we correct mistakes</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>When we get something wrong we fix the story and publish a note on our <a href="/corrections/">Corrections</a> page. Corrections are free to everyone, even when the story they correct is not.</p>
<!-- /wp:paragraph -->

